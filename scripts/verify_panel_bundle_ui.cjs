const {chromium}=require('playwright');
const fs=require('fs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({ignoreHTTPSErrors:true,viewport:{width:1920,height:1080}});
 fs.mkdirSync('panel-preview',{recursive:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('https://127.0.0.1:8080/panel');
 await page.locator('#standalone-auth').waitFor();
 await page.screenshot({path:'panel-preview/login.png'});
 await page.locator('#standalone-auth input[type=email]').fill('owner@example.com');
 await page.locator('#standalone-auth input[type=password]').fill('PreviewPassword123');
 await page.locator('#standalone-auth button').click();
 await page.locator('body.standalone-ready').waitFor();
 await page.locator('#fg-panel-header').waitFor();
 await page.screenshot({path:'panel-preview/devices-ar.png'});
 await page.locator('#fg-panel-nav [data-view=users]').click();
 await page.locator('#fgdu-name').fill('previewuser');
 await page.locator('#fgdu-password').fill('PersonalPassword123');
 const createdResponse=page.waitForResponse(r=>r.url().endsWith('/panel/api/direct/users')&&r.request().method()==='POST');
 await page.locator('#fgdu-create-button').click();
 const created=await createdResponse;if(!created.ok())throw Error('Create user: '+await created.text());
 await page.waitForFunction(()=>document.querySelector('#fgdu-user').textContent.includes('previewuser'));
 await page.screenshot({path:'panel-preview/users-ar.png'});
 await page.locator('#standalone-tools button').first().click();
 await page.waitForFunction(()=>document.documentElement.dir==='ltr');
 await page.screenshot({path:'panel-preview/users-en.png'});
 await page.setViewportSize({width:390,height:844});
 await page.locator('#standalone-tools button').first().click();
 await page.waitForFunction(()=>document.documentElement.dir==='rtl');
 await page.screenshot({path:'panel-preview/users-mobile-ar.png',fullPage:true});
 await page.locator('#standalone-tools button').last().click();
 await page.locator('#standalone-auth').waitFor();
 if(errors.length)throw Error(errors.join('\n'));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
